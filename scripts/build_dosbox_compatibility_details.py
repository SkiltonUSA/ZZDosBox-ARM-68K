#!/usr/bin/env python3
"""Build offline MUI and Markdown detail views from the factual snapshot."""
import json
import struct
import zlib
from pathlib import Path
from scrape_dosbox_compatibility import ROOT,c_string,markdown

def c_lines(value):
    # Only our generated line breaks are admitted; source text is escaped by c_string.
    return r'"\012"'.join(c_string(line) for line in value.split('\n'))

def generate():
    source=ROOT/'amiga/dosbox/compatibility/dosbox-details.json'
    snapshot=json.loads(source.read_text());games=sorted(snapshot['games'],key=lambda g:g['game_id'])
    index=json.loads((ROOT/'amiga/dosbox/compatibility/dosbox-compatibility.json').read_text())
    assert {g['game_id'] for g in games}=={g['game_id'] for g in index['games']}
    assert len(games)==snapshot['count']==index['unique_games']
    header=['/* Generated by scripts/build_dosbox_compatibility_details.py. */',
        '#ifndef ZZ_COMPAT_DETAILS_DATA_H','#define ZZ_COMPAT_DETAILS_DATA_H',
        'struct compat_game_details { unsigned id,comments; const char *publisher,*tester,*history,*date,*author,*preview,*discussion; };',
        'static const struct compat_game_details compat_game_details[] = {']
    md=['# DOSBox per-game reports','',
        f'{len(games):,} games. All recorded version ratings are retained, including conflicting reports.', '',
        'Source: [DOSBox compatibility database](https://www.dosbox.com/comp_list.php?letter=a).', '',
        'These community reports concern upstream DOSBox, not verified ZZDosBox results.',
        'Automatic topic overviews index every cached comment. Counts describe mentions, not verified fixes; topics can overlap.',
        'Latest-comment previews quote at most 20 words per game; follow the original report for complete comments.',
        'A missing preview means that the page has no comments. Ratings are not performance measurements.', '',
        '[Alphabetical summary](amiga-dosbox-compatibility.md)', '']
    records=[]
    packed=[]
    for g in sorted(games,key=lambda g:(g['title'].casefold(),g['game_id'])):
        assert g['discussion']['indexed_comments']==g['comment_count']==len(g['discussion']['entries'])
        versions=g['versions'];history='|'.join(v['dosbox_version']+'  '+v['status']+('  '+str(v['rating_percent'])+'%' if v['rating_percent'] is not None else '') for v in versions)
        assert '|' not in ''.join(v['dosbox_version'] for v in versions)
        strings=[g['publisher'],g['tested_by'],history,g['latest_comment_at'],g['latest_comment_author'],g['note_preview'],g['discussion']['summary']]
        # Strip control characters from external text before it reaches MUI.
        strings=[''.join(c if (ord(c)>=32 and ord(c)!=127) or c=='\n' else ' ' for c in s) for s in strings]
        payload=struct.pack('>I',g['comment_count'])+b''.join(v.encode('latin-1',errors='replace')+b'\0' for v in strings)
        packed.append((g['game_id'],payload))
        records.append((g['game_id'],'{'+str(g['game_id'])+','+str(g['comment_count'])+','+','.join(c_lines(s) for s in strings)+'},'))
        md += [f'<a id="game-{g["game_id"]}"></a>',f'## {markdown(g["title"])}','',
            f'Publisher: {markdown(g["publisher"] or "Not listed")} · Year: {markdown(g["year"])} · Tested by: {markdown(g["tested_by"] or "Not listed")}', '',
            f'[Original report]({g["source_url"]}) · {g["comment_count"]} community comments', '',
            '| DOSBox version | Status | Rating |','| --- | --- | ---: |']
        for v in versions:
            rating=str(v['rating_percent'])+'%' if v['rating_percent'] is not None else '—'
            md.append(f'| {v["dosbox_version"]} | {v["status"]} | {rating} |')
        if g['discussion']['summary']:
            md += ['', '### Discussion overview', ''] + [markdown(line)+'  ' for line in g['discussion']['summary'].splitlines()]
        if g['note_preview']:
            md += ['',f'Latest comment preview — {markdown(g["latest_comment_author"])} ({g["latest_comment_at"]}):','',
                   '> '+markdown(g['note_preview'])]
        else:md += ['','No community comments on this report.']
        md.append('')
    header += [record for _,record in sorted(records)]
    header+=['};','#define COMPAT_DETAILS_COUNT (sizeof(compat_game_details)/sizeof(compat_game_details[0]))','#endif','']
    packed.sort();offset=20+len(packed)*16;index=bytearray();payloads=bytearray()
    for gid,payload in packed:
        assert len(payload)<=8192
        index+=struct.pack('>IIII',gid,offset,len(payload),zlib.crc32(payload));offset+=len(payload);payloads+=payload
    checksum=zlib.crc32(index)
    target=ROOT/'.context/amiga/dosbox-launcher';target.mkdir(parents=True,exist_ok=True)
    (target/'Compatibility.dat').write_bytes(b'ZZCD0001'+struct.pack('>III',len(packed),checksum,offset)+index+payloads)
    meta='/* Generated detail store identity; no report text is linked into the launcher. */\n'
    meta+=f'#define COMPAT_STORE_COUNT {len(packed)}u\n#define COMPAT_STORE_INDEX_CRC 0x{checksum:08x}u\n#define COMPAT_STORE_BYTES {offset}u\n#define COMPAT_STORE_RECORD_MAX 8192u\n'
    (ROOT/'amiga/dosbox/compatibility/details_meta.h').write_text(meta)
    (ROOT/'amiga/dosbox/compatibility/details.h').write_text('\n'.join(header))
    (ROOT/'docs/amiga-dosbox-game-details.md').write_text('\n'.join(md))
    print(len(games),'games;',sum(len(g['versions']) for g in games),'version reports;',sum(bool(g['note_preview']) for g in games),'comment previews')
if __name__=='__main__':generate()
